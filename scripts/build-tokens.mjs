#!/usr/bin/env node
// Writes app/styles/tokens.css from lib/design/tokens.ts. `--stdout` prints it instead, which the
// tokens-css test compares with the committed file so nobody edits the output by hand.
// Until the shell flips (Phase 2) every rule is scoped to SCOPE, the /press proof route.
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import {
  CARE_PAPER,
  COLOR_ROLES,
  DURATIONS,
  EASES,
  FONTS,
  PALETTES,
  RADII,
  SENSE_VALUES,
  SPACE,
  TYPE,
  WIDTHS,
  Z,
} from '../lib/design/tokens.ts'

const SCOPE = '.press'
const OUT = join(import.meta.dirname, '..', 'app', 'styles', 'tokens.css')

const HIGH = ['[data-contrast="high"]', '[data-contrast="extra-high"]']

function block(selectors, declarations, indent = '') {
  const body = Object.entries(declarations)
    .map(([name, value]) => `${indent}  --${name}: ${value};`)
    .join('\n')
  return `${indent}${selectors.join(',\n' + indent)} {\n${body}\n${indent}}`
}

function colors(name) {
  return Object.fromEntries(COLOR_ROLES.map((role) => [role, PALETTES[name][role]]))
}

/** One palette for light, and the same in dark both when chosen and when the device asks for it. */
function themed(selectors, palette, darkPalette) {
  const under = (theme) => selectors.map(({ html, own }) => `:where(html${theme}${html}) ${SCOPE}${own}`)
  return [
    block(selectors.map(({ html, own }) => (html ? `:where(html${html}) ${SCOPE}${own}` : `${SCOPE}${own}`)), colors(palette)),
    block(under('[data-theme="dark"]'), colors(darkPalette)),
    `@media (prefers-color-scheme: dark) {
${block(under('[data-theme="auto"]'), colors(darkPalette), '  ')}
}`,
  ]
}

function sense(name) {
  const s = SENSE_VALUES[name]
  return {
    motion: s.motion,
    grain: s.grain,
    misreg: `${s.misreg}px`,
    'misreg-hover': `${s.misregHover}px`,
    tilt: Number(s.tilt.toFixed(4)),
    lift: `${s.lift}px`,
  }
}

export function renderTokensCss() {
  const statics = {
    focus: 'var(--ink)',
    'care-paper': `color-mix(in oklab, var(--${CARE_PAPER.ink}) ${CARE_PAPER.weight * 100}%, var(--${CARE_PAPER.over}))`,
    'font-body': FONTS.body,
    'font-display': FONTS.display,
    ...Object.fromEntries(Object.entries(TYPE).flatMap(([k, v]) => [[`t-${k}`, v.size], [`lh-${k}`, v.leading]])),
    ...Object.fromEntries(SPACE.map((px, i) => [`s-${i + 1}`, `${px}px`])),
    ...Object.fromEntries(Object.entries(WIDTHS).map(([k, v]) => [`w-${k}`, v])),
    ...Object.fromEntries(Object.entries(RADII).map(([k, v]) => [`r-${k}`, v])),
    'border-control': '2px',
    ...Object.fromEntries(Object.entries(DURATIONS).map(([k, v]) => [`d-${k}`, `${v}ms`])),
    ...Object.fromEntries(Object.entries(EASES).map(([k, v]) => [`e-${k}`, v])),
    ...Object.fromEntries(Object.entries(Z).map(([k, v]) => [`z-${k}`, v])),
    ...sense('gentle'),
  }
  const quiet = ':where([data-sense="quiet"])'
  const parts = [
    '/* Generated by scripts/build-tokens.mjs from lib/design/tokens.ts. Do not edit by hand. */',
    '/* Every selector has the weight of one class, so the order below decides: theme, then sense, then contrast. */',
    block([SCOPE], statics),
    ...themed([{ html: '', own: '' }], 'light', 'dark'),
    ...themed([{ html: '', own: quiet }], 'lightQuiet', 'darkQuiet'),
    ...themed(HIGH.map((html) => ({ html, own: '' })), 'lightHigh', 'darkHigh'),
    block([`${SCOPE}${quiet}`], sense('quiet')),
    block([`${SCOPE}:where([data-sense="lively"])`], sense('lively')),
    block([`:where(html[data-contrast="extra-high"]) ${SCOPE}`], {
      rule: 'var(--rule-strong)',
      'border-control': '3px',
      grain: 0,
      misreg: '0px',
      'misreg-hover': '0px',
    }),
    block([`:where(html[data-reduce-motion="true"]) ${SCOPE}`], { motion: 0 }),
    `@media (prefers-reduced-motion: reduce) {\n${block([SCOPE], { motion: 0 }, '  ')}\n}`,
  ]
  return parts.join('\n\n') + '\n'
}

if (process.argv[1] && import.meta.filename === (await import('node:fs')).realpathSync(process.argv[1])) {
  if (process.argv.includes('--stdout')) process.stdout.write(renderTokensCss())
  else {
    writeFileSync(OUT, renderTokensCss())
    console.log(`build-tokens: wrote ${OUT}`)
  }
}
